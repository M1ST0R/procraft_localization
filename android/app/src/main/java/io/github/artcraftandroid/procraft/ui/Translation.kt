private val artworkCount = Regex("""^([0-9]+) artworks$""")
private val quickMenuName = Regex("""^QuickMenu ([0-9]+)$""")
private val deleteArtworkCount = Regex("""^Delete ([0-9]+) artworks?\?$""")
private val frameNumber = Regex("""^Frame ([0-9]+)$""")
private val sharedLayerWarning = Regex("""^“(.+)” is on every mesh of this texture set\.$""")
private val blockedLayerMessage = Regex("""^“(.+)” can't be changed while (.+)\.$""")
private val trackedTime = Regex("""^([0-9]+)h ([0-9]+)m$""")
private val layerSetCount = Regex("""^([0-9]+) of ([0-9]+)$""")

internal fun localizeUiText(source: String): String {
    russianUi[source]?.let { return it }
    if (source == source.uppercase()) {
        russianUi.entries.firstOrNull { it.key.uppercase() == source }?.let { return it.value }
    }

    quickMenuName.matchEntire(source)?.let { return "Быстрое меню ${it.groupValues[1]}" }
    frameNumber.matchEntire(source)?.let { return "Кадр ${it.groupValues[1]}" }
    sharedLayerWarning.matchEntire(source)?.let { return "«${it.groupValues[1]}» используется на всех сетках этого набора текстур." }
    blockedLayerMessage.matchEntire(source)?.let { match ->
        val reason = when (match.groupValues[2]) {
            "it is hidden" -> "пока он скрыт"
            "its layer is hidden" -> "пока скрыт его слой"
            "its group is hidden" -> "пока скрыта его группа"
            "a layer in it is hidden" -> "пока в нём есть скрытый слой"
            "another layer is shown alone" -> "пока отображается только другой слой"
            "it is locked" -> "пока он заблокирован"
            "its alpha is locked" -> "пока заблокирован его альфа-канал"
            else -> return@let
        }
        return "«${match.groupValues[1]}» нельзя изменить, $reason."
    }
    trackedTime.matchEntire(source)?.let {
        return "${it.groupValues[1]} ч ${it.groupValues[2]} мин"
    }
    layerSetCount.matchEntire(source)?.let {
        return "${it.groupValues[1]} из ${it.groupValues[2]}"
    }
    artworkCount.matchEntire(source)?.let {
        val count = it.groupValues[1].toIntOrNull() ?: return@let
        val word = when (count % 100) {
            in 11..14 -> "работ"
            else -> when (count % 10) {
                1 -> "работа"
                in 2..4 -> "работы"
                else -> "работ"
            }
        }
        return "$count $word"
    }
    deleteArtworkCount.matchEntire(source)?.let {
        val count = it.groupValues[1].toIntOrNull() ?: return@let
        val word = when (count % 100) {
            in 11..14 -> "работ"
            else -> when (count % 10) {
                1 -> "работу"
                in 2..4 -> "работы"
                else -> "работ"
            }
        }
        return "Удалить $count $word?"
    }

    return when {
        Regex("""^([0-9]+(?:[.][0-9]+)?)s$""").matchEntire(source)?.let { it.groupValues[1] } != null ->
            source.dropLast(1).replace('.', ',') + " с"
        source.startsWith("A picture tip: ") -> {
            val detail = source.removePrefix("A picture tip: ").removeSuffix(".")
            val missing = ", which the file doesn't hold. As in Krita, its default tip stands in: round, 40 px across"
            if (detail.endsWith(missing)) {
                "Графический наконечник «" + detail.removeSuffix(missing) + "» отсутствует в файле. Как и в Krita, используется стандартный круглый наконечник диаметром 40 px."
            } else {
                "Графический наконечник: " + detail + "."
            }
        }
        source.startsWith("An auto tip: a ") -> {
            val detail = source.removePrefix("An auto tip: a ").removeSuffix(".").split(", its edge ", limit = 2)
            val shape = when (detail.firstOrNull()) {
                "circle" -> "круг"
                "rectangle" -> "прямоугольник"
                else -> detail.firstOrNull().orEmpty()
            }
            val edge = when (detail.getOrNull(1)) {
                "soft" -> "мягкий"
                "Gaussian" -> "гауссовский"
                "default" -> "стандартный"
                else -> detail.getOrNull(1).orEmpty()
            }
            "Автоматический наконечник: " + shape + ", край — " + edge + "."
        }
        source.startsWith("Its pattern: ") ->
            "Шаблон: " + source.removePrefix("Its pattern: ").removeSuffix(".") + "."
        source.startsWith("Filter: ") -> when (source.removePrefix("Filter: ").removeSuffix(".")) {
            "Gaussian blur" -> "Фильтр: размытие по Гауссу."
            "Blur" -> "Фильтр: размытие."
            "Unsharp mask" -> "Фильтр: маска нерезкости."
            else -> "Фильтр: " + source.removePrefix("Filter: ")
        }
        source.startsWith("Filter \"") && source.endsWith("\": not drawn here.") ->
            "Фильтр «" + source.removePrefix("Filter \"").removeSuffix("\": not drawn here.") +
                "»: отображение пока не поддерживается."
        source.contains(" follows ") && source.endsWith(".") -> {
            val split = source.removeSuffix(".").split(" follows ", limit = 2)
            val label = russianUi[split[0]] ?: split[0]
            val sensors = split.getOrNull(1).orEmpty().split(", ").joinToString(", ") {
                russianUi[it] ?: it
            }
            label + " зависит от " + sensors + "."
        }
        source.endsWith(" by") -> {
            val label = source.removeSuffix(" by")
            (russianUi[label] ?: label) + ": зависит от"
        }
        source.startsWith("Version ") -> "Версия " + source.removePrefix("Version ")
        source.startsWith("Made by ") -> "Автор: " + source.removePrefix("Made by ")
        source.startsWith("Last reset point: ") -> "Последняя точка сброса: " + source.removePrefix("Last reset point: ")
        source.startsWith("This is ProCraft's 32-bit version") ->
            "Это 32-разрядная версия ProCraft для старых планшетов. На этом планшете используется 64-разрядная версия, которую ожидает Android: установите APK, имя которого заканчивается на arm64.apk, поверх этой версии — ваши работы сохранятся."
        source.startsWith("Painting on this model may not go as expected because of:\n") ->
            "Рисование на этой модели может работать некорректно из-за:\n" +
                source.substringAfter('\n').lines().joinToString("\n") { russianUi[it] ?: it }
        source.startsWith("Selection Threshold ") -> "Порог выделения " + source.removePrefix("Selection Threshold ")
        source.startsWith("Threshold ") -> "Порог " + source.removePrefix("Threshold ")
        source.startsWith("Delete “") && source.endsWith("”?") -> "Удалить " + source.removePrefix("Delete “").removeSuffix("”?").let { "«$it»?" }
        else -> source
    }
}

